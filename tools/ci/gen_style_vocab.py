#!/usr/bin/env python3
"""Generate the shared C++, TypeScript, and JavaScript style vocabulary."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]

# Every vocabulary enum gets its decoder names from this same inventory.
ENUMS = (
    ("sizeRoles", "TextSizeRole", "TEXT_SIZE_ROLE"),
    ("weights", "TextWeight", "TEXT_WEIGHT"),
    ("colors", "TextColor", "TEXT_COLOR"),
    ("family", "TextFamily", "TEXT_FAMILY"),
    ("wrap", "TextWrap", "TEXT_WRAP"),
    ("truncation", "TextTruncation", "TEXT_TRUNCATION"),
    ("align", "TextAlign", "TEXT_ALIGN"),
)


def js_name(key):
    first, *rest = key.split("_")
    return first.lower() + "".join(part.title() for part in rest)


def enum_lines(name, prefix, entries):
    lines = ["    enum %s" % name, "    {"]
    items = list(entries.items())
    for index, (key, value) in enumerate(items):
        comma = "," if index + 1 < len(items) else ""
        lines.append("      %s_%s = %d%s" % (prefix, key, value, comma))
    lines.extend(["    };", ""])
    return lines


def enum_entries(vocab, kind):
    entries = {"UNSET": 0, **vocab[kind]} if kind in ("colors", "family") else vocab[kind]
    if kind in ("sizeRoles", "family"):
        entries = {**entries, "COUNT": len(entries)}
    return entries


def generate_cpp(vocab):
    lines = [
        "// Generated by tools/ci/gen_style_vocab.py. Do not edit.",
        "#ifndef LOKA_APP_STYLE_STYLE_VOCAB_ENUMS_HPP",
        "#define LOKA_APP_STYLE_STYLE_VOCAB_ENUMS_HPP",
        "",
        "namespace loka",
        "{",
        "  namespace app",
        "  {",
    ]
    for kind, enum, prefix in ENUMS:
        lines += enum_lines(enum, prefix, enum_entries(vocab, kind))
    sizes = ", ".join(str(value) for value in vocab["sizes"])
    lines += [
        "    template <int N> struct FontSize;",
        "    namespace detail",
        "    {",
        "      enum { kStyleVocabularySizeCount = %d };" % len(vocab["sizes"]),
        "      extern const int StyleVocabularySizes[];",
        "      extern const int StyleVocabularySizeCount;",
        "    }",
        "  } // namespace app",
        "} // namespace loka",
        "",
        "#endif // LOKA_APP_STYLE_STYLE_VOCAB_ENUMS_HPP",
        "",
        "#if defined(LOKA_STYLE_VOCAB_DEFINE_SIZES) && !defined(LOKA_APP_STYLE_STYLE_VOCAB_SIZES_HPP)",
        "#define LOKA_APP_STYLE_STYLE_VOCAB_SIZES_HPP",
        "",
        "namespace loka",
        "{",
        "  namespace app",
        "  {",
    ]
    for size in vocab["sizes"]:
        lines += [
            "    template <> struct FontSize<%d> : public TextStyle" % size,
            "    {",
            "      FontSize() : TextStyle()",
            "      {",
            "        this->size_ = TextSizeValue::points(%d);" % size,
            "      }",
            "    };",
            "",
        ]
    lines += [
        "    /** Semantic font roles, initialized per TU like Bold. */",
    ]
    for key in vocab["sizeRoles"]:
        name = "".join(part.title() for part in key.split("_"))
        lines.append("    static const TextStyle %s = TextStyle(TextSizeValue::role(TEXT_SIZE_ROLE_%s));" % (name, key))
    lines.append("    /** Standard-palette roles and inks, initialized per TU like Bold. */")
    for key in vocab["colors"]:
        lines.append("    static const TextStyle %s = TextStyle().color(TEXT_COLOR_%s);" % (key.title(), key))
    lines += [
        "  } // namespace app",
        "} // namespace loka",
        "",
        "#endif // generated size specialisations",
        "",
        "#if defined(LOKA_STYLE_VOCAB_DEFINE_STORAGE) && !defined(LOKA_APP_STYLE_STYLE_VOCAB_STORAGE_HPP)",
        "#define LOKA_APP_STYLE_STYLE_VOCAB_STORAGE_HPP",
        "",
        "namespace loka",
        "{",
        "  namespace app",
        "  {",
        "    namespace detail",
        "    {",
        "      const int StyleVocabularySizes[] = {%s};" % sizes,
        "      const int StyleVocabularySizeCount =",
        "          static_cast<int>(sizeof(StyleVocabularySizes) / sizeof(StyleVocabularySizes[0]));",
        "    }",
        "  } // namespace app",
        "} // namespace loka",
        "",
        "#endif // generated vocabulary storage",
        "",
    ]
    lines += [
        "#if defined(LOKA_STYLE_VOCAB_DEFINE_NAMES) && !defined(LOKA_APP_STYLE_STYLE_VOCAB_NAMES_HPP)",
        "#define LOKA_APP_STYLE_STYLE_VOCAB_NAMES_HPP",
        "",
        "/** Opt-in decoder names; include Style.hpp before requesting this section. */",
        "namespace loka",
        "{",
        "  namespace app",
        "  {",
        "    namespace detail",
        "    {",
    ]
    for index, (kind, enum, prefix) in enumerate(ENUMS):
        if index:
            lines.append("")
        lines += [
            "      struct %sName" % enum,
            "      {", "        const char *name;", "        %s value;" % enum, "      };",
            "      static const %sName StyleVocabulary%s[] = {" % (enum, ("SizeRoles" if kind == "sizeRoles" else kind.title())),
        ]
        for key in vocab[kind]:
            value = "%s_%s" % (prefix, key)
            name = key.lower() if kind != "sizeRoles" else js_name(key)
            lines.append('          {"%s", %s},' % (name, value))
        lines.append("      };")
    lines += [
        "    } // namespace detail",
        "  } // namespace app",
        "} // namespace loka",
        "",
        "#endif // generated vocabulary names",
        "",
    ]
    return "\n".join(lines)


def ts_type(value):
    return {"fontSize": "FontSize", "weight": "TextWeight", "italic": "boolean", "underline": "boolean", "color": "TextColor", "family": "TextFamily",
            "wrap": "TextWrap", "truncation": "TextTruncation", "align": "TextAlign"}[value]


def union(values):
    return " | ".join(str(value) for value in values)


def generate_typescript(vocab):
    lines = [
        "// Generated by tools/ci/gen_style_vocab.py. Do not edit.",
        "export type FontSize = %s;" % union(vocab["sizes"]),
        "export type TextSizeRole = %s;" % union(json.dumps(js_name(key)) for key in vocab["sizeRoles"]),
        "export type TextWeight = %s;" % union(json.dumps(key.lower()) for key in vocab["weights"]),
        "export type TextColor = %s;" % union(json.dumps(key.lower()) for key in vocab["colors"]),
        "export type TextFamily = %s;" % union(json.dumps(key.lower()) for key in vocab["family"]),
        "export type TextWrap = %s;" % union(json.dumps(key.lower()) for key in vocab["wrap"]),
        "export type TextTruncation = %s;" % union(json.dumps(key.lower()) for key in vocab["truncation"]),
        "export type TextAlign = %s;" % union(json.dumps(key.lower()) for key in vocab["align"]),
        "",
    ]
    for interface in ("TextStyle", "BlockStyle"):
        lines.append("export interface %s {" % interface)
        for field in vocab["fields"][interface]:
            if interface == "TextStyle" and field == "fontSize":
                # The JS door accepts any integer and snaps it to the nearest
                # vocabulary size (ties down), or a semantic role name.
                lines.append("  /** Integer points snap to the nearest FontSize, ties down; roles resolve on the rail. */")
                lines.append("  size?: number | TextSizeRole;")
                continue
            lines.append("  %s?: %s;" % (field, ts_type(field)))
        lines.extend(["}", ""])
    lines += [
        "/**",
        " * JS globals (signatures only; node globals are not declared in this file):",
        " * Text(value: string | Seat, style?: TextStyle, block?: BlockStyle)",
        " * Markup(markup: string, style?: TextStyle, block?: BlockStyle)",
        " * ZStack(...children).expStaticBlurUnit(): immutable ZStack tree; refuses other node kinds.",
        " * Static blur fills the ground extent without stretching its child. Tree depth is at most 11.",
        " */",
        "",
    ]
    return "\n".join(lines)


def generate_runtime(vocab):
    sizes = ",".join(str(value) for value in vocab["sizes"])
    family = json.dumps(enum_entries(vocab, "family"), separators=(",", ":"))
    return ("// Generated by tools/ci/gen_style_vocab.py. Do not edit.\n"
            "module.exports = {sizes:[%s],family:%s};\n") % (sizes, family)


def validate_web_skins(vocab):
    rows = vocab.get("webSkins")
    if not isinstance(rows, list) or not rows or len(rows) > 2147483647:
        raise ValueError("webSkins must be a nonempty array within signed import range")
    names = set()
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get("name"), str) or row["name"] in names:
            raise ValueError("webSkins names must be unique strings")
        names.add(row["name"])
        spacing = row.get("spacing")
        if not isinstance(spacing, list) or len(spacing) != 3 or any(
                type(value) is not int or not 0 <= value <= 32767 for value in spacing):
            raise ValueError("webSkins spacing must be three integers in 0..32767")
    if rows[0]["name"] != "web":
        raise ValueError("webSkins first row must be web")


def generate_skins(vocab):
    lines = ["// Generated by tools/ci/gen_style_vocab.py. Do not edit.",
             "#ifndef LOKA_WEB_SKINS_HPP", "#define LOKA_WEB_SKINS_HPP",
             '#include "app/layout/RailSpacing.hpp"',
             "enum", "{", "  WEB_SKIN_DEFAULT = 0,", "  WEB_SKIN_COUNT = %d" % len(vocab["webSkins"]), "};",
             "static const loka::app::layout::RailSpacing WebSkinSpacing[] = {"]
    lines += ["    loka::app::layout::RailSpacing(%d, %d, %d)," % tuple(row["spacing"])
              for row in vocab["webSkins"]]
    return "\n".join(lines + ["};", "#endif", ""])


def resolved_schema(vocab):
    wire = vocab["wire"]["textDescriptor"]
    fields = ["version", "count"] + wire["fields"]
    return {
        "webSkinSelection": {"default": 0, "names": [row["name"] for row in vocab["webSkins"]]},
        "version": wire["version"], "fields": fields, "count": len(fields),
        "word": "signed-int32", "sizes": vocab["sizes"],
        "enums": {kind: enum_entries(vocab, kind) for kind, _, _ in ENUMS},
        "ranges": {
            "sizeKind": {"NONE": 0, "POINTS": 1, "ROLE": 2},
            "sizePayload": {"NONE": [0], "POINTS": [-32768, 32767],
                            "ROLE": sorted(vocab["sizeRoles"].values())},
            "weight": [-1] + sorted(vocab["weights"].values()),
            "italic": [-1, 0, 1], "underline": [-1, 0, 1],
            "family": [0] + sorted(vocab["family"].values()),
            "color": [0] + sorted(vocab["colors"].values())}}


def fingerprint(schema):
    value = 2166136261
    for byte in json.dumps(schema, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode('utf-8'):
        value = ((value ^ byte) * 16777619) & 0xffffffff
    return value


def field_name(name):
    import re
    return re.sub(r'([a-z])([A-Z])', r'\1_\2', name).upper()


def generate_wire(vocab):
    schema = resolved_schema(vocab)
    lines = ["// Generated by tools/ci/gen_style_vocab.py. Do not edit.",
             "#ifndef LOKA_WEB_STYLE_WIRE_HPP", "#define LOKA_WEB_STYLE_WIRE_HPP", "",
             "enum WebTextField", "{"]
    for index, name in enumerate(schema["fields"]):
        name = "WORD_COUNT" if name == "count" else field_name(name)
        lines.append("  WEB_TEXT_FIELD_%s = %d," % (name, index))
    lines += ["  WEB_TEXT_FIELD_COUNT = %d" % schema["count"], "};",
              "static const int kWebTextDescriptorVersion = %d;" % schema["version"],
              "static const unsigned long kWebTextWireFingerprint = 0x%08xUL;" % fingerprint(schema),
              "", "#endif", ""]
    return "\n".join(lines)


def generate_web(vocab):
    schema = resolved_schema(vocab)
    web = {kind: enum_entries(vocab, kind) for kind, _, _ in ENUMS}
    web["sizes"] = vocab["sizes"]
    web["webMeasureStatus"] = vocab["webMeasureStatus"]
    web["webButtonGeometry"] = vocab["webButtonGeometry"]
    web["wire"] = {"version": schema["version"], "count": schema["count"],
                   "fields": {name: i for i, name in enumerate(schema["fields"])},
                   "ranges": schema["ranges"], "fingerprint": fingerprint(schema)}
    return ("// Generated by tools/ci/gen_style_vocab.py. Do not edit.\n"
            + "var LokaWebStyle = " + json.dumps(web, separators=(",", ":")) + ";\n"
            + "/** Cost: bootstrap once; at most one comparison per generated name, no resource rows. */\n"
            + "LokaWebStyle.resolveSkin = function(name) {\n"
            + "".join("  if (name === %s) return %d;\n" % (json.dumps(row["name"]), index)
                      for index, row in enumerate(vocab["webSkins"]))
            + "  return 0;\n};\n")


def generate_projection(vocab):
    lines = ["// Generated by tools/ci/gen_style_vocab.py. Do not edit.",
             "#ifndef LOKA_WEB_TEXT_CONSTANTS_HPP", "#define LOKA_WEB_TEXT_CONSTANTS_HPP",
             "enum WebMeasureStatus", "{"]
    lines += ["  WEB_MEASURE_%s = %d," % item for item in vocab["webMeasureStatus"].items()]
    lines += ["};", "/** Web-specific chrome geometry; not common style vocabulary. */"]
    lines += ["static const int kWebButton%s = %d;" % (key[0].upper()+key[1:], value)
              for key, value in vocab["webButtonGeometry"].items()]
    return "\n".join(lines + ["#endif", ""])


OUTPUTS = {
    Path("web/src/WebSkins.hpp"): generate_skins,
    Path("web/src/WebTextConstants.hpp"): generate_projection,
    Path("common/app/style/StyleVocab.hpp"): generate_cpp,
    Path("docs/smirkycard/loka-style.d.ts"): generate_typescript,
    Path("tools/style-vocab.runtime.js"): generate_runtime,
    Path("web/js/style-vocab.js"): generate_web,
    Path("web/src/WebStyleWire.hpp"): generate_wire,
}


def write(root, relative, content):
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-root", type=Path, default=ROOT)
    parser.add_argument("--vocab", type=Path, default=ROOT / "tools/style-vocab.json")
    args = parser.parse_args()
    vocab = json.loads(args.vocab.read_text(encoding="utf-8"))
    validate_web_skins(vocab)
    for path, renderer in OUTPUTS.items():
        write(args.output_root, path, renderer(vocab))



if __name__ == "__main__":
    main()
