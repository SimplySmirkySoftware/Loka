#!/usr/bin/env python3
"""Canonical schema identity, independent of JSON formatting and object order."""
import copy
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location('generator', ROOT / 'tools/ci/gen_style_vocab.py')
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)
vocab = json.loads((ROOT / 'tools/style-vocab.json').read_text())
fingerprint = lambda v: g.fingerprint(g.resolved_schema(v))
original = fingerprint(vocab)
def reverse_objects(value):
    if isinstance(value, dict):
        return {k: reverse_objects(v) for k, v in reversed(list(value.items()))}
    if isinstance(value, list):
        return [reverse_objects(v) for v in value]
    return value
assert fingerprint(json.loads(json.dumps(reverse_objects(vocab), indent=4))) == original
remap = copy.deepcopy(vocab)
remap['weights']['NORMAL'], remap['weights']['BOLD'] = 1, 0
assert fingerprint(remap) != original
reorder = copy.deepcopy(vocab)
fields = reorder['wire']['textDescriptor']['fields']
fields[0], fields[1] = fields[1], fields[0]
assert fingerprint(reorder) != original
assert len(g.resolved_schema(reorder)['fields']) == len(g.resolved_schema(vocab)['fields'])
assert g.fingerprint({}) == 1415952421  # Independent FNV-1a vector for UTF-8 '{}'.
print('schema: formatting/key-order stable; enum-remap/field-reorder sensitive; FNV vector passed')

assert g.resolved_schema(vocab).get('webSkinSelection') == {'default': 0, 'names': ['web', 'win32', 'macos', 'classic']}
for change in ('reorder', 'rename', 'spacing'):
    altered = copy.deepcopy(vocab)
    if change == 'reorder':
        altered['webSkins'][1:3] = reversed(altered['webSkins'][1:3])
    elif change == 'rename':
        altered['webSkins'][1]['name'] = 'other'
    else:
        altered['webSkins'][1]['spacing'][0] += 1
    assert (fingerprint(altered) == original) == (change == 'spacing')
for rows in ([], {}, [{'name':'other','spacing':[1,2,3]}],
             [{'name':'web','spacing':[True,2,3]}], [{'name':'web','spacing':[-1,2,3]}],
             [{'name':'web','spacing':[32768,2,3]}], [{'name':'web','spacing':[1.5,2,3]}],
             [{'name':'web','spacing':[1,2]}], [{'name':'web','spacing':[1,2,3]}]*2,
             [{'name':1,'spacing':[1,2,3]}]):
    altered = copy.deepcopy(vocab)
    altered['webSkins'] = rows
    try:
        g.validate_web_skins(altered)
    except ValueError:
        pass
    else:
        raise AssertionError('invalid skins admitted')
g.validate_web_skins(vocab)
print('skins: mapping sensitive; spacing invariant; invalid tables refused')

with tempfile.TemporaryDirectory(prefix='loka-skin-validation-') as temporary:
    directory = Path(temporary)
    invalid = copy.deepcopy(vocab)
    invalid['webSkins'][-1]['spacing'][0] = True
    source = directory / 'invalid.json'
    source.write_text(json.dumps(invalid))
    output = directory / 'output'
    result = subprocess.run([sys.executable, str(ROOT / 'tools/ci/gen_style_vocab.py'),
                             '--vocab', str(source), '--output-root', str(output)],
                            capture_output=True, text=True)
    assert result.returncode != 0 and 'ValueError' in result.stderr
    assert not output.exists(), 'validation precedes every generated output'
print('skins: invalid input produces no outputs')

# Pin the extension output itself, including a valid non-default rename/reorder.
skin_output = Path('tools/vscode-loka/src/skins.ts')
assert skin_output in g.OUTPUTS, 'extension skins registered in OUTPUTS'
for change, names in [('rename', ['web', 'other"</script>', 'macos', 'classic']),
                      ('reorder', ['web', 'macos', 'win32', 'classic'])]:
    altered = copy.deepcopy(vocab)
    if change == 'rename':
        altered['webSkins'][1]['name'] = names[1]
    else:
        altered['webSkins'][1:3] = reversed(altered['webSkins'][1:3])
    g.validate_web_skins(altered)
    assert g.OUTPUTS[skin_output](altered) == (
        '// Generated by tools/ci/gen_style_vocab.py. Do not edit.\n'
        'export const skinNames: readonly string[] = ' + json.dumps(names) + ';\n')

# Run the real checker in an isolated tree; every other output remains current.
import shutil
with tempfile.TemporaryDirectory(prefix='loka-extension-skins-') as temporary:
    root = Path(temporary)
    (root / 'tools/ci').mkdir(parents=True)
    for name in ['gen_style_vocab.py', 'check_style_vocab.py']:
        shutil.copyfile(ROOT / 'tools/ci' / name, root / 'tools/ci' / name)
    shutil.copyfile(ROOT / 'tools/style-vocab.json', root / 'tools/style-vocab.json')
    for relative, renderer in g.OUTPUTS.items():
        g.write(root, relative, renderer(vocab))
    def check():
        return subprocess.run([sys.executable, str(root / 'tools/ci/check_style_vocab.py')],
                              capture_output=True, text=True)
    assert check().returncode == 0, 'positive control: all generated outputs current'
    for missing in [False, True]:
        if missing:
            (root / skin_output).unlink()
        else:
            (root / skin_output).write_text('export const skinNames: readonly string[] = ["stale"];\n')
        result = check()
        assert result.returncode == 1, 'skin-only stale/missing output must fail checker'
        assert str(skin_output) in result.stderr
print('extension skins: renamed/reordered JSON output; skin-only stale and missing checker controls passed')

# Every rejected look must leave every output byte untouched, including when
# the invalid row is last (validation cannot be interleaved with writes).
invalid_looks = []
base = vocab['webSkins'][-1]['look']
for field in base:
    missing = dict(base); del missing[field]; invalid_looks.append(missing)
extra = dict(base, pressed='#ffffff'); invalid_looks.append(extra)
for field, values in [('radius', [-1,17,True,False,1.5,'4',None]),
                      ('scheme', ['dark','LIGHT',None,[]])]:
    for value in values:
        invalid_looks.append(dict(base, **{field:value}))
for field in g.LOOK_COLOR_FIELDS:
    for value in ['red','#ABCDEF','#12345','#123456\n','Canvas;','Canvas}', 'Canvas"',None,True,[]]:
        invalid_looks.append(dict(base, **{field:value}))
with tempfile.TemporaryDirectory(prefix='loka-look-') as temporary:
    root = Path(temporary)
    source = root / 'input.json'
    for relative in g.OUTPUTS:
        g.write(root, relative, 'unchanged sentinel\n')
    for look in invalid_looks:
        altered = copy.deepcopy(vocab)
        altered['webSkins'][-1]['look'] = look
        source.write_text(json.dumps(altered))
        result = subprocess.run([sys.executable, str(ROOT/'tools/ci/gen_style_vocab.py'),
                                 '--vocab', str(source), '--output-root', str(root)], capture_output=True)
        assert result.returncode != 0
        assert all((root/p).read_text() == 'unchanged sentinel\n' for p in g.OUTPUTS)
for radius in [0,16]:
    altered = copy.deepcopy(vocab); altered['webSkins'][0]['look']['radius'] = radius
    g.validate_web_skins(altered)
for row in vocab['webSkins']:
    paint = g.skin_look(row['look'])
    assert set(paint) == {'root','button','cell','disabledText'}
    assert ('color-scheme' in paint['root']) == (row['look']['scheme'] == 'light')
    assert paint['cell']['border-radius'] == '0px'
print('look: closed fields, colours, scheme and exact integer radius; all outputs untouched on refusal')

paint_only = copy.deepcopy(vocab)
paint_only['webSkins'][1]['look']['text'] = '#123456'
g.validate_web_skins(paint_only)
assert fingerprint(paint_only) == original, 'paint is outside wire identity; JS and wasm are paired builds'
